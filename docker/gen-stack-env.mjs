#!/usr/bin/env node
// Generates the THROWAWAY secrets for docker/docker-compose.stack.yml. Nothing secret is stored in the repo: this writes
// docker/.env.stack (git-ignored and docker-ignored) with freshly generated random values, mode 0600.
//
//   node docker/gen-stack-env.mjs                    # dev-like stack: sandbox payments/payouts, dev OTP printed in the API log
//   node docker/gen-stack-env.mjs --mode prod-like   # NODE_ENV=production + every money provider `disabled` (boots with the production gates on)
//   node docker/gen-stack-env.mjs --out <file>       # somewhere else
//   node docker/gen-stack-env.mjs --force            # overwrite (rotating the PII keys orphans data in an existing stack volume!)
//
// What it will NEVER write: Razorpay keys, a live key of any kind, REAL_MONEY_ENABLED=true. The API refuses all of those in
// production and this stack is for local use only. Values are written unquoted with PEM newlines as the two characters "\n"
// (the form `docker run --env-file`, docker compose and the API's own loader all accept).
import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const option = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};

const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(option('--out', join(here, '.env.stack')));
const mode = option('--mode', 'dev');
if (!['dev', 'prod-like'].includes(mode)) {
  console.error(`--mode must be "dev" or "prod-like" (got "${mode}")`);
  process.exit(2);
}
if (existsSync(target) && !flag('--force')) {
  console.error(`${target} already exists — not overwriting (the PII keys inside it define the data in the stack's database volume).`);
  console.error('Pass --force to replace it, then `docker compose ... down -v` to drop the old volume.');
  process.exit(1);
}

const pair = generateKeyPairSync('ec', { namedCurve: 'P-256' });
const pem = (key, type) => key.export({ type, format: 'pem' }).toString().trim().replace(/\n/g, '\\n');
const b64 = () => randomBytes(32).toString('base64');

const values = {
  STACK_MODE: mode,
  // database (hex => URL-safe, no escaping needed in DATABASE_URL)
  POSTGRES_USER: 'tokengo',
  POSTGRES_DB: 'tokengo',
  POSTGRES_PASSWORD: randomBytes(24).toString('hex'),
  // application secrets
  JWT_PRIVATE_KEY_PEM: pem(pair.privateKey, 'pkcs8'),
  JWT_PUBLIC_KEY_PEM: pem(pair.publicKey, 'spki'),
  PII_ENCRYPTION_KEY_B64: b64(),
  PII_HASH_KEY_B64: b64(),
  PAYMENT_WEBHOOK_SECRET_B64: b64(),
  // provider selection — the production gates (apps/api/src/shared-kernel/config.ts) refuse anything else when NODE_ENV=production
  NODE_ENV: mode === 'prod-like' ? 'production' : 'development',
  SMS_PROVIDER: mode === 'prod-like' ? 'disabled' : 'console',
  PAYMENT_PROVIDER: mode === 'prod-like' ? 'disabled' : 'sandbox',
  PAYOUT_PROVIDER: mode === 'prod-like' ? 'disabled' : 'sandbox',
  REAL_MONEY_ENABLED: 'false',
  // Production refuses local file storage and requires a bucket name to BOOT. This is a placeholder that does not exist: the API starts
  // and serves everything except file uploads (which fail against it). A dev-mode stack uses local storage and needs no bucket.
  ...(mode === 'prod-like' ? { S3_BUCKET: 'tokengo-prodlike-placeholder-no-such-bucket' } : {}),
  LOG_LEVEL: 'info',
  // host ports (bound to 127.0.0.1 only)
  STACK_API_PORT: '3100',
  STACK_ADMIN_PORT: '3101',
  STACK_DB_PORT: '55434',
};

const body =
  `# Generated by docker/gen-stack-env.mjs (${mode}). THROWAWAY, local use only. Git-ignored; never commit, never reuse elsewhere.\n` +
  Object.entries(values)
    .map(([k, v]) => `${k}=${v}`)
    .join('\n') +
  '\n';
writeFileSync(target, body, { mode: 0o600 });
console.log(`Wrote ${target} (${mode}, ${Object.keys(values).length} values, new random secrets). Values are not printed.`);
